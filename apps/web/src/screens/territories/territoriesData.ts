export interface TerritoryHierarchy {
  country: string;
  state: string;
  city: string;
  zone: string;
  area: string;
  pincode: string;
  microTerritory?: string;
}

export interface TerritoryItem {
  id: string;
  code: string;
  name: string;
  regionArea: string;
  city: string;
  managerName: string;
  managerAvatar: string;
  managerRole: string;
  executivesCount: number;
  teamLeadsCount: number;
  monthlyTarget: number;
  monthlyAchieved: number;
  monthlyTargetFormatted: string;
  monthlyAchievedFormatted: string;
  performancePercentage: number;
  status: 'Active' | 'Inactive';
  color: string;
  description: string;
  createdOn: string;
  lastUpdated: string;
  createdBy: string;
  areaKm2: number;
  perimeterKm: number;
  estBusinesses: number;
  estPopulation: string;
  activeBusinessesCount: number;
  totalVisitsThisMonth: number;
  pathPoints: [number, number][]; // [lat, lng]
  hierarchy: TerritoryHierarchy;
}

